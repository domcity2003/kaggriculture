"""Contender: forecast marginal returns, diverse investments and coordinated labor.

Uses only the observation/configuration and standard library. All economic
estimates are local forecasts, never replay information or hidden state.
"""
import math

CROPS = {
    "WHEAT": (10, 2, 4), "CARROT": (20, 2, 3),
    "MELON": (80, 10, 12), "TOMATO": (50, 8, 11),
    "STRAWBERRY": (100, 10, 16),
}
ANIMALS = {"COW": (400, "MILK", 8, 2, "PASTURE", 6),
           "SHEEP": (500, "WOOL", 6, 3, "PASTURE", 6),
           "GOOSE": (300, "EGG", 4, 1, "COOP", 4)}
PARAMS = {
    "WHEAT": (25, 400, "sqrt", .8, "log", .2),
    "CARROT": (35, 450, "hinge", 1., "sqrt", .7),
    "TOMATO": (60, 200, "hinge", .4, "sqrt", .6),
    "STRAWBERRY": (120, 100, "sqrt", .7, "linear", 1.6),
    "MELON": (250, 300, "log", .2, "sq", 3.6),
    "EGG": (50, 332, "hinge", .4, "log", .2),
    "MILK": (160, 122, "sqrt", .6, "linear", 1.6),
    "WOOL": (200, 105, "log", .2, "sq", 3.2),
    "FERTILIZER": (100, 200, "linear", .4, "linear", .4),
}
SHOPS = {"BAKERY": ("EGG", "WHEAT"),
    "PIZZA_SHOP": ("MILK", "TOMATO", "WHEAT"),
    "BRUNCH_SPOT": ("EGG", "WHEAT", "STRAWBERRY"),
    "YARN_STORE": ("WOOL",), "ICE_CREAM_SHOP": ("STRAWBERRY", "MILK", "WHEAT"),
    "PET_CAFE": ("CARROT",), "SMOOTHIE_SHOP": ("STRAWBERRY", "MILK"),
    "FARMERS_MARKET": ("WHEAT", "CARROT", "TOMATO", "STRAWBERRY")}
# Items whose price collapses fast under glut: the first seller into a shared
# market takes the high prices and a late dump lands on a floor that never
# recovers (there is no drift back toward the neutral inventory).
STEEP = {k for k, v in PARAMS.items() if v[4] == "sq" or (v[4] == "linear" and v[5] >= 1.5)}
_MEM = {}

# Tunable policy knobs. Variants are generated by rewriting this dict, so every
# candidate differs from its parent only in values recorded here.
CFG = {
    "travel": 2.5,
    "cow_cap": 14.0,
    "other_cap": 8.0,
    "herd_cap": 20.0,
    "open_wheat": 10.0,
    "open_melon": 8.0,
    "melon_age": 10.0,
    "stick": 0.35,
    "deliver": 0.0,
    "melon_water": 0.0,
    "global_assign": 1,
    "land_occ": 0.78,
    "land_buf": 350.0,
    "seed_batch": 5.0,
    "plant_prio": 80.0,
    "order_mode": 1,
    "hire_slots": 3.0,
    "rush": 0.5,
    "rush_min": 150.0,
}
# Engine yield caps for one-time crops: watering inside
# [ceil(max_yield_day/2) .. max_yield_day] adds +1 (or +2 fertilized) up to MAXY.
MAXY = {"WHEAT": 6, "CARROT": 4, "MELON": 6}
MAX_YIELD_DAY = {"WHEAT": 4, "CARROT": 3, "MELON": 12}


def dist(a, b):
    return abs(a[0]-b[0]) + abs(a[1]-b[1])


def move(a, b):
    if a[0] != b[0]:
        return ["EAST" if a[0] < b[0] else "WEST"]
    if a[1] != b[1]:
        return ["SOUTH" if a[1] < b[1] else "NORTH"]
    return ["PASS"]


def price(item, inventory, overrides=None):
    base, t, lo, lt, hi, ht = PARAMS[item]
    anchor = 10000
    if overrides and item in overrides:
        p = overrides[item]
        base, t = p.get("base", base), p.get("T", t)
        lo, lt = p.get("below_func", lo), p.get("below_target", lt)
        hi, ht = p.get("above_func", hi), p.get("above_target", ht)
        anchor = p.get("I0", anchor)
    x = abs(inventory-anchor)
    func, target = (lo, lt) if inventory < anchor else (hi, ht)
    if func == "sqrt":
        f = math.sqrt(x/t)
    elif func == "sq":
        f = (x/t)**2
    elif func in ("log", "log10"):
        f = math.log1p(x)/math.log1p(t)
    elif func == "hinge":
        u = x/t
        f = u + 8*max(0, u-1)**2
    else:
        f = x/t
    return max(1, round(base + (1 if inventory < anchor else -1)*target*base*f))


def crop_events(crop, planted, fertilized):
    if crop == "WHEAT":
        return [(planted+(3 if fertilized else 4), 5 if fertilized else 4)]
    if crop == "CARROT":
        return [(planted+3, 4 if fertilized else 3)]
    if crop == "MELON":
        return [(planted+10, 6)]
    ages = (8, 9, 10, 11) if crop == "TOMATO" else (10, 12, 14, 16)
    return [(planted+a, 2 if fertilized else 1) for a in ages]


class Forecast:
    def __init__(self, obs, cfg, end):
        self.day, self.end = obs["day"], end
        self.overrides = cfg.get("marketParams", {})
        self.inventory = {k: [float(v)]*(end+1) for k, v in obs["market"]["inventory"].items()}
        self.demand = {k: (0. if k == "FERTILIZER" else 1.) for k in PARAMS}
        for shop in obs["town"]["unlocked_shops"]:
            for k in SHOPS[shop]:
                self.demand[k] += (2 if len(SHOPS[shop]) == 1 else 1)*6
        expected = {k: 0. for k in PARAMS}
        for products in SHOPS.values():
            for k in products:
                expected[k] += 6*(2 if len(products) == 1 else 1)/8
        nshops = len(obs["town"]["unlocked_shops"])
        for d in range(self.day, end+1):
            future_area = 0
            for i in range(8-nshops):
                unlock = ((self.day//3)+1+i)*3
                future_area += max(0, d-unlock)
            for k in PARAMS:
                self.inventory[k][d] -= self.demand[k]*(d-self.day)+expected[k]*future_area*.65
        # Standing production from both farms. Predict ordinary upkeep,
        # while respecting remaining lifetime and current product already held.
        for p, farm in enumerate(obs["farms"]):
            for row in farm["tiles"]:
                for tile in row:
                    if not isinstance(tile, dict):
                        continue
                    if "animal" in tile:
                        _, product, first, interval, _, cap = ANIMALS[tile["animal"]]
                        self.add(product, self.day, tile.get("yield_units", 0))
                        for d in range(self.day+1, end+1):
                            age = d-tile["placed_day"]
                            if age >= first and (age-first)%interval == 0:
                                self.add(product, d, min(cap, interval+1))
                            self.add("WHEAT", d, -.85)
                            self.add("FERTILIZER", d, .55)
                    elif tile.get("kind") == "PLANT":
                        c, planted = tile["crop"], tile["planted_day"]
                        fert = tile.get("fertilized_until_day", -1) >= self.day
                        if c in ("TOMATO", "STRAWBERRY"):
                            self.add(c, self.day, tile.get("yield_units", 0))
                            for d, n in crop_events(c, planted, True):
                                if d > self.day:
                                    self.add(c, d, n)
                        else:
                            d, n = crop_events(c, planted, fert)[0]
                            self.add(c, max(self.day, d), max(n, tile.get("yield_units", 0)))
                        # Opponent staples tend to be replanted. Do not assume
                        # they preserve a long-lived premium monoculture.
                        if p != obs["player"] and c in ("WHEAT", "CARROT"):
                            cycle = 5 if c == "WHEAT" else 4
                            for d in range(max(self.day, planted+cycle)+cycle, end+1, cycle):
                                self.add(c, d, 4 if c == "WHEAT" else 3)

    def add(self, item, day, amount):
        for d in range(max(self.day, day), self.end+1):
            self.inventory[item][d] += amount

    def quote(self, item, day, n=0):
        return price(item, self.inventory[item][min(day, self.end)]+n/2, self.overrides)

    def crop(self, c, start, fertilizer):
        events = crop_events(c, start, fertilizer)
        events = [(d, n) for d, n in events if d <= self.end]
        if not events:
            return (-1e9, [])
        revenue = sum(self.quote(c, d, n)*n for d, n in events)
        fert_cost = 0
        if fertilizer:
            fert_cost = (2 if c in ("TOMATO", "STRAWBERRY") else 1)*self.quote("FERTILIZER", start+2)
        duration = min(self.end, crop_events(c, start, fertilizer)[-1][0])-start+1
        # Crop maintenance and harvest time valued against other farm jobs.
        profit = revenue-CROPS[c][0]-fert_cost
        score = profit/duration - 2.0*(1+len(events))/duration
        return score, events


def make_plan(obs, cfg, end, memory):
    farm = obs["farms"][obs["player"]]
    day = obs["day"]
    forecast = Forecast(obs, cfg, end)
    animals = {a: 0 for a in ANIMALS}
    own_crops = {c: 0 for c in CROPS}
    available = []
    for y, row in enumerate(farm["tiles"]):
        for x, t in enumerate(row):
            if isinstance(t, dict) and "animal" in t:
                animals[t["animal"]] += 1
            elif isinstance(t, dict) and t.get("kind") == "PLANT":
                own_crops[t["crop"]] += 1
            elif t is None or (isinstance(t, dict) and t.get("kind") == "WEED"):
                available.append((x, y))
    private = obs["private"]
    for a in ANIMALS:
        animals[a] += private["shed"].get(a, 0)+sum(i.get(a, 0) for i in private["inventories"])
    animal_total = sum(animals.values())
    best_animal = None
    best_roi = 0
    # Limit setup to one at a time; reassess after purchases and placement.
    if day < end-7 and animal_total < CFG["herd_cap"]:
        for a, (cost, product, first, interval, _, cap) in ANIMALS.items():
            revenue = 0.
            for d in range(day+1, end+1):
                revenue += max(0, forecast.quote("FERTILIZER", d)-1)*.7
                revenue -= forecast.quote("WHEAT", d)+8
                age = d-day
                if age >= first and (age-first)%interval == 0:
                    n = min(cap, first if age == first else interval+1)
                    revenue += n*forecast.quote(product, d, n)
            roi = (revenue-cost)/(end-day)
            # Prevent speculative overinvestment into a single fragile market.
            if animals[a] >= (CFG["cow_cap"] if a == "COW" else CFG["other_cap"]):
                roi = -1
            if roi > best_roi:
                best_roi, best_animal = roi, a
        if day <= 1:
            best_animal = "COW" if animals["COW"] < 2 else "SHEEP" if animals["SHEEP"] < 2 else None
        elif day < 5 and animal_total >= 6:
            best_animal = None
    plan = {}
    center = (len(farm["tiles"])//2-1,)*2
    # Outer plots suit crops; livestock is placed close to storage by scheduler.
    available.sort(key=lambda p: (dist(p, center), p))
    can_fert = animal_total >= 3 or private["shed"].get("FERTILIZER", 0) >= 3
    for pos in available:
        candidates = []
        for c in CROPS:
            for fert in (False, True) if can_fert and c != "MELON" else (False,):
                score, events = forecast.crop(c, day, fert)
                # Establish short-cycle cash flow and a diversified first harvest.
                if day <= 1:
                    desired = {"WHEAT": CFG["open_wheat"], "MELON": CFG["open_melon"]}
                    if c not in desired or own_crops[c] >= desired[c]:
                        continue
                    score = 150 if c == "WHEAT" else 120
                candidates.append((score, c, fert, events))
        if not candidates:
            continue
        score, c, fert, events = max(candidates)
        if score <= 0:
            continue
        plan[pos] = (c, score, fert)
        own_crops[c] += 1
        for d, n in events:
            forecast.add(c, d, n)
    memory["plan"] = plan
    memory["animal"] = best_animal
    memory["animal_roi"] = best_roi
    memory["forecast"] = forecast
    memory["animals"] = animal_total
    memory["counts"] = animals
    return memory


def agent(obs, configuration=None):
    cfg = configuration or {}
    farm = obs["farms"][obs["player"]]
    private = obs["private"]
    day, hour = obs["day"], obs["hour"]
    turns = cfg.get("turnsPerDay", 24)
    last = cfg.get("episodeSteps", 720)-2
    step = obs.get("step", day*turns+hour)
    end, remaining = last//turns, last-step+1
    tiles = farm["tiles"]
    size = len(tiles)
    half = size//2
    access = [(half-1, half-1), (half, half-1), (half-1, half), (half, half)]
    key = obs["player"]
    if step == 0 or key not in _MEM:
        _MEM[key] = {}
    memory = _MEM[key]
    # Replan after harvests, investment changes and town arrivals.
    signature = (day, sum(t is None or (isinstance(t, dict) and t.get("kind")=="WEED") for row in tiles for t in row),
                 tuple(private["shed"].get(a, 0) for a in ANIMALS),
                 tuple(sum(isinstance(t, dict) and t.get("animal")==a for row in tiles for t in row) for a in ANIMALS))
    if memory.get("signature") != signature or hour % 6 == 0:
        make_plan(obs, cfg, end, memory)
        memory["signature"] = signature
    forecast = memory["forecast"]
    plans = memory["plan"]
    current_prices = obs["market"]["prices"]
    positions = [farm["farmer"]]+list(farm["hands"])
    # Worker commitment: remember where each unit was heading last turn so a
    # part-completed walk is not abandoned when another job briefly outranks it.
    last_target = memory.get("targets", {}) if memory.get("target_step") == step-1 else {}
    new_target = {}
    invs = [dict(i) for i in private["inventories"]]
    shed = dict(private["shed"])
    seeds = dict(private["seeds"])
    used = set()
    actions = [["PASS"] for _ in positions]
    crop_need = {}
    active_animals = sum("animal" in t for row in tiles for t in row if isinstance(t, dict))
    # Jobs are tile-level chains; a worker with resources finishes local upkeep
    # before moving on. Recomputed each turn to recover from contested/no-op work.
    jobs = []
    for y, row in enumerate(tiles):
        for x, tile in enumerate(row):
            pos = (x, y)
            if tile is None:
                if pos in plans and hour <= turns-4:
                    c, score, fert = plans[pos]
                    crop_need[c] = crop_need.get(c, 0)+1
                    jobs.append((pos, "plant", c, max(15, min(CFG["plant_prio"], score)), tile))
            elif not isinstance(tile, dict):
                continue
            elif "animal" in tile:
                a = tile["animal"]
                _, product, first, interval, _, cap = ANIMALS[a]
                if tile.get("yield_units", 0):
                    n = tile["yield_units"]
                    jobs.append((pos, "harvest", product, max(45, min(500, current_prices[product]*n*.7)), tile))
                if tile.get("fertilizer_available"):
                    jobs.append((pos, "collect", "FERTILIZER", max(20, current_prices["FERTILIZER"]*.8), tile))
                # Keep valuable animals alive; stop paying for products that can
                # no longer be produced before the end or cannot cover feed.
                next_prod = next((d for d in range(day+1, end+1) if d-tile["placed_day"] >= first and (d-tile["placed_day"]-first)%interval==0), None)
                keep = day < end and (current_prices["FERTILIZER"]+current_prices[product]*(1+1/interval) > current_prices["WHEAT"]+5)
                if keep and not tile["fed_today"]:
                    urgent = tile["consecutive_unfed"] >= 1
                    jobs.append((pos, "feed", "WHEAT", 600 if urgent else 100, tile))
                if next_prod and keep and not tile["cared_today"] and (current_prices[product] > 8):
                    jobs.append((pos, "care", "", max(35, min(140, current_prices[product]*.6)), tile))
            elif tile.get("kind") == "PLANT":
                c = tile["crop"]
                age = day-tile["planted_day"]
                n = tile.get("yield_units", 0)
                ongoing = c in ("TOMATO", "STRAWBERRY")
                mature = age >= CROPS[c][1]
                fert_active = tile.get("fertilized_until_day", -1) >= day
                if ongoing:
                    due = n >= 2 or (n and (age >= CROPS[c][2] or hour > 14 or day == end))
                    if due:
                        jobs.append((pos, "harvest", c, max(80, min(450, n*current_prices[c]*.7)), tile))
                    if age >= CROPS[c][2] and not n:
                        if day+2 <= end:
                            jobs.append((pos, "dig", c, 50, tile))
                        continue
                else:
                    target = 3 if c == "WHEAT" and n >= 5 else 4 if c == "WHEAT" else 3 if c == "CARROT" else CFG["melon_age"]
                    due = mature and (age >= target or day == end)
                    if due and (tile["watered_today"] or day == end or n >= (6 if c in ("WHEAT", "MELON") else 4)):
                        jobs.append((pos, "harvest", c, max(100, min(600, current_prices[c]*n)), tile))
                        continue
                if not tile["watered_today"]:
                    urgent = tile["consecutive_unwatered"] >= 1
                    # Evaluate fertilizer's opportunity cost at its sell price.
                    window = c == "WHEAT" and age in (2, 3) or c == "CARROT" and age == 2 or c == "TOMATO" and age in (7, 10) or c == "STRAWBERRY" and age in (9, 13)
                    extra = 2 if c in ("WHEAT", "STRAWBERRY", "TOMATO") else 1
                    use_fert = window and not fert_active and current_prices[c]*extra > current_prices["FERTILIZER"]+8
                    prio = 550 if urgent else 130
                    if CFG["melon_water"] and c in MAXY:
                        start = (MAX_YIELD_DAY[c]+1)//2
                        if start <= age <= MAX_YIELD_DAY[c] and n < MAXY[c]:
                            gain = min(MAXY[c]-n, 2 if fert_active else 1)
                            prio = max(prio, gain*current_prices[c]*CFG["melon_water"])
                    jobs.append((pos, "waterfert" if use_fert else "water", c, prio, tile))
            elif tile.get("kind") == "WEED" and pos in plans and day+2 <= end:
                jobs.append((pos, "dig", "", 25, tile))

    # Handle animal carriers first so crop workers cannot occupy setup targets.
    order = sorted(range(len(positions)), key=lambda i: (not any(invs[i].get(a,0) for a in ANIMALS), i))
    deferred = {}
    for i in order:
        pos, inv = positions[i], invs[i]
        home = min(access, key=lambda p: dist(pos, p))
        dh = dist(pos, home)
        carrying = sum(inv.values())
        carried_animal = next((a for a in ANIMALS if inv.get(a)), None)
        if carrying and day == end and remaining <= dh+3:
            actions[i] = ["DROP"] if dh == 0 else move(pos, home)
            continue
        if carried_animal:
            structure = ANIMALS[carried_animal][4]
            sites = []
            for y, row in enumerate(tiles):
                for x, t in enumerate(row):
                    q = (x,y)
                    if q in used:
                        continue
                    if t is None or (isinstance(t,dict) and t.get("kind")==structure and "animal" not in t):
                        dd = dist(pos,q)
                        proximity = min(dist(q,h) for h in access)
                        sites.append((dd+proximity*1.4-(4 if isinstance(t,dict) else 0),q,t))
            if sites:
                _, q, t = min(sites, key=lambda x: (x[0],x[1]))
                used.add(q)
                actions[i] = move(pos,q) if tuple(pos)!=q else ["PLACE",carried_animal] if isinstance(t,dict) else ["BUILD_"+structure]
                continue
        # Take setup animals at the depot, with stock reserved across workers.
        if dh == 0 and hour < turns-8:
            a = next((a for a in ANIMALS if shed.get(a,0)>0), None)
            if a:
                shed[a] -= 1
                actions[i] = ["PICKUP",a,1]
                continue
        # Shed-adjacent workers equip resources before heading out. Limit
        # allocation so a single worker cannot monopolize the daily stock.
        if dh == 0 and hour < turns-7:
            if active_animals and inv.get("WHEAT",0)==0 and shed.get("WHEAT",0)>0:
                n = min(3, shed["WHEAT"])
                shed["WHEAT"] -= n
                actions[i] = ["PICKUP","WHEAT",n]
                continue
            if inv.get("FERTILIZER",0)==0 and shed.get("FERTILIZER",0)>0:
                n = min(2, shed["FERTILIZER"])
                shed["FERTILIZER"] -= n
                actions[i] = ["PICKUP","FERTILIZER",n]
                continue
        candidates = []
        for q, kind, item, value, tile in jobs:
            if q in used:
                continue
            dd = dist(pos,q)
            if hour+dd >= turns:
                continue
            if kind == "plant" and (seeds.get(item,0)<=0 or hour+dd+2>=turns):
                continue
            if kind == "feed" and inv.get("WHEAT",0)<=0:
                continue
            if kind == "care" and not tile["fed_today"]:
                continue
            if day == end:
                if kind not in ("harvest","collect","water","waterfert"):
                    continue
                if kind.startswith("water") and (tile.get("crop") not in CROPS or day-tile["planted_day"]<CROPS[tile["crop"]][1]):
                    continue
                work = 2 if kind.startswith("water") else 1
                if dd+work+min(dist(q,h) for h in access)+1>remaining:
                    continue
            # Urgency escalates near nightfall; travel amortized across local
            # action chains to avoid constantly rerouting workers.
            adjusted = value
            if kind in ("water", "waterfert", "feed") and hour > 14:
                adjusted *= 2
            candidates.append((adjusted/(1+dd*CFG["travel"])*(1+CFG["stick"] if q==last_target.get(i) else 1), -dd, q, kind, item))
        # A full pair of hands is worth nothing until it reaches the shed: ripe
        # melons sitting in an inventory cannot be sold, and the first seller
        # into a shared market takes the high prices.
        if CFG["deliver"] and carrying:
            carry_val = sum(n*current_prices.get(k,0) for k,n in inv.items() if k in PARAMS)
            if carry_val:
                score = carry_val*CFG["deliver"]/(1+dh*CFG["travel"])
                if not candidates or score > max(candidates)[0]:
                    actions[i] = ["DROP"] if dh==0 else move(pos,home)
                    continue
        # Rushing home all season costs more field work than it earns, but a
        # hand full of ripe melons is a different case: that market craters
        # within a few turns and whoever reaches it second sells into a floor.
        if CFG["rush"] and carrying:
            steep_val = sum(n*current_prices.get(k, 0) for k, n in inv.items() if k in STEEP)
            if steep_val >= CFG["rush_min"]:
                score = steep_val*CFG["rush"]/(1+dh*CFG["travel"])
                if not candidates or score > max(candidates)[0]:
                    actions[i] = ["DROP"] if dh == 0 else move(pos, home)
                    continue
        if CFG["global_assign"] and candidates:
            # Defer: assigning in worker order lets whoever is considered first
            # claim the nearby work and strands the rest with long walks.
            deferred[i] = candidates
            continue
        if candidates:
            _, _, q, kind, item = max(candidates)
            used.add(q)
            new_target[i] = q
            if kind == "plant":
                seeds[item] -= 1
            if tuple(pos) != q:
                actions[i] = move(pos,q)
            else:
                mapping = {"plant":["PLANT",item],"harvest":["HARVEST"],
                    "collect":["COLLECT_FERTILIZER"],"feed":["FEED"],
                    "care":["CARE"],"water":["WATER"],"dig":["DIG"]}
                actions[i] = ["FERTILIZE"] if kind=="waterfert" and inv.get("FERTILIZER",0)>0 else ["WATER"] if kind=="waterfert" else mapping[kind]
        elif carrying and (day==end or hour<turns-3):
            actions[i] = ["DROP"] if dh==0 else move(pos,home)

    if deferred:
        # Joint assignment: rank every (worker, job) pair together and take the
        # best pairings first, so a job goes to its nearest free worker rather
        # than to whichever worker happened to be considered earlier.
        pool = []
        for i, cands in deferred.items():
            for sc, negd, q, kind, item in cands:
                pool.append((sc, negd, i, q, kind, item))
        pool.sort(key=lambda t: (-t[0], t[1]))
        mapping = {"plant":["PLANT"],"harvest":["HARVEST"],
            "collect":["COLLECT_FERTILIZER"],"feed":["FEED"],
            "care":["CARE"],"water":["WATER"],"dig":["DIG"]}
        placed = set()
        for sc, negd, i, q, kind, item in pool:
            if i in placed or q in used:
                continue
            if kind == "plant" and seeds.get(item, 0) <= 0:
                continue
            placed.add(i)
            used.add(q)
            new_target[i] = q
            if kind == "plant":
                seeds[item] -= 1
            pos = positions[i]
            if tuple(pos) != q:
                actions[i] = move(pos, q)
            elif kind == "plant":
                actions[i] = ["PLANT", item]
            elif kind == "waterfert":
                actions[i] = ["FERTILIZE"] if invs[i].get("FERTILIZER",0) > 0 else ["WATER"]
            else:
                actions[i] = mapping[kind]
        for i in deferred:
            if i in placed:
                continue
            pos, inv = positions[i], invs[i]
            home = min(access, key=lambda p: dist(pos, p))
            dh = dist(pos, home)
            if sum(inv.values()) and (day == end or hour < turns-3):
                actions[i] = ["DROP"] if dh == 0 else move(pos, home)
    memory["targets"] = new_target
    memory["target_step"] = step
    # Liquidate saleable stock while preserving working supplies. Match newly
    # dropped resources so they can be sold in this same market phase.
    for i, a in enumerate(actions):
        if a[0]=="DROP":
            for k,n in invs[i].items():
                shed[k] = shed.get(k,0)+n
    feed_need = sum(1 for row in tiles for t in row if isinstance(t,dict) and "animal" in t and not t["fed_today"])
    held_wheat = sum(v.get("WHEAT",0) for v in invs)
    reserve_wheat = max(0, feed_need+2-held_wheat) if day<end else 0
    reserve_fert = min(12, max(0, len([j for j in jobs if j[1]=="waterfert"]))) if day<end else 0
    market = []
    budget = farm["money"]
    for item in sorted(PARAMS, key=lambda k: -shed.get(k,0)*current_prices[k]):
        reserve = reserve_wheat if item=="WHEAT" else reserve_fert if item=="FERTILIZER" else 0
        n = max(0,shed.get(item,0)-reserve)
        if n:
            market.append(["SELL",item,n])
            budget += n*current_prices[item]*.85
    # Maintain feed before committing more capital. Purchases arrive next turn.
    if day<end and hour<turns-4 and shed.get("WHEAT",0)<reserve_wheat:
        n = reserve_wheat-shed.get("WHEAT",0)
        if budget > n*current_prices["WHEAT"]:
            market.append(["BUY_PRODUCT","WHEAT",n])
            budget -= n*current_prices["WHEAT"]
    owned = sum(t!="LOCKED" for row in tiles for t in row)
    target_hands = 7 if owned<=25 else 9 if owned<=50 else 11
    if hour<=2:
        count = len(farm["hands"])
        a,b = 1,1
        for _ in range(count):
            a,b = b,a+b
        while count<target_hands and budget>=a and len(market)<10:
            market.append(["HIRE"])
            budget -= a
            a,b=b,a+b
            count+=1
    # Buy land early enough to recover its cost; avoid distant fourth quadrant
    # until evidence establishes that its much higher price is justified.
    extras = len(farm["unlocked_quadrants"])-1
    occupied = sum(isinstance(t,dict) and t.get("kind")!="WEED" for row in tiles for t in row)
    if extras<2 and day<18 and occupied>=owned*CFG["land_occ"] and budget>[1000,2000][extras]+CFG["land_buf"]:
        market.append(["BUY_LAND"])
        budget -= [1000,2000][extras]
    wanted_animal = memory["animal"]
    unplaced = sum(private["shed"].get(a,0)+sum(i.get(a,0) for i in invs) for a in ANIMALS)
    if wanted_animal and not unplaced and hour<turns-8 and budget>ANIMALS[wanted_animal][0]+150:
        market.append(["BUY_ANIMAL",wanted_animal,1])
        budget-=ANIMALS[wanted_animal][0]
    if hour<turns-4:
        priorities = sorted(crop_need, key=lambda c: -max((p[1] for p in plans.values() if p[0]==c),default=0))
        for c in priorities:
            needed = max(0,crop_need[c]-private["seeds"].get(c,0))
            n=min(needed, max(0,int((budget-30)//CROPS[c][0])), int(CFG["seed_batch"]))
            if n:
                market.append(["BUY_SEED",c,n])
                budget-=n*CROPS[c][0]
    cap = cfg.get("maxMarketOrdersPerTurn", 10)
    if CFG["order_mode"] and len(market) > cap:
        # Orders are built sells-first and hires-before-growth, so a turn with
        # more than `cap` orders silently drops the tail -- which is land,
        # animals and seeds, on exactly the day-start turns where hires flood
        # the list. Rank by importance instead of build order, and bound how
        # many slots hires may take; deferred hires simply retry next turn.
        rank = {"SELL": 0, "BUY_PRODUCT": 1, "BUY_LAND": 2,
                "BUY_ANIMAL": 3, "BUY_SEED": 4, "HIRE": 5}
        hires = [o for o in market if o and o[0] == "HIRE"][:int(CFG["hire_slots"])]
        rest = [o for o in market if not (o and o[0] == "HIRE")]
        market = sorted(rest + hires, key=lambda o: rank.get(o[0] if o else "", 9))
    return {"farmer":actions[0],"hands":actions[1:],"market":market[:cap]}
